# CampaignPlayer
# ═══════════════════════════════════════════════════════════════════════


class TestCampaignPlayer:
    def test_defaults_and_autogenerated_id(self):
        p = CampaignPlayer(name="Juan")
        assert p.name == "Juan"
        assert p.id.startswith("plr_")
        assert len(p.id) == 12  # plr_ + 8 hex
        assert p.metadata == {}

    def test_explicit_id(self):
        p = CampaignPlayer(name="Ana", id="plr_custom01")
        assert p.id == "plr_custom01"

    def test_to_dict(self):
        p = CampaignPlayer(name="Juan", metadata={"role": "GM"})
        d = p.to_dict()
        assert d["name"] == "Juan"
        assert d["id"].startswith("plr_")
        assert d["metadata"]["role"] == "GM"
        assert len(d) == 3

    def test_from_dict(self):
        data = {"id": "plr_abc12345", "name": "María", "metadata": {"role": "player"}}
        p = CampaignPlayer.from_dict(data)
        assert p.id == "plr_abc12345"
        assert p.name == "María"
        assert p.metadata == {"role": "player"}

    def test_from_dict_empty(self):
        p = CampaignPlayer.from_dict({})
        assert p.name == ""
        # id is autogenerated by __post_init__ when passed ""
        assert p.id.startswith("plr_")

    def test_from_dict_missing_fields(self):
        p = CampaignPlayer.from_dict({"name": "Luis"})
        assert p.name == "Luis"
        # id is autogenerated because it's missing from data
        assert p.id.startswith("plr_")
        assert p.metadata == {}

    def test_roundtrip(self):
        p = CampaignPlayer(name="Ana", metadata={"note": "test"})
        j = p.to_dict()
        p2 = CampaignPlayer.from_dict(j)
        assert p2.name == p.name
        assert p2.id == p.id
        assert p2.metadata == p.metadata


