class TestHelpers:
    def test_now_returns_iso_string(self):
        ts = _now()
        assert isinstance(ts, str)
        assert "T" in ts
        assert len(ts) >= 20

    def test_parse_list_with_none(self):
        assert _parse_list(None) == []

    def test_parse_list_with_list(self):
        assert _parse_list([1, 2]) == [1, 2]

    def test_parse_list_with_string(self):
        assert _parse_list("not a list") == []

    def test_parse_str_with_str(self):
        assert _parse_str("hello") == "hello"

    def test_parse_str_with_none(self):
        assert _parse_str(None) == ""

    def test_parse_int_with_int(self):
        assert _parse_int(42) == 42

    def test_parse_int_with_bool(self):
        # bool is a subclass of int in Python, but our guard
        # checks isinstance(value, bool) and returns 0
        assert _parse_int(True) == 0

    def test_parse_dict(self):
        assert _parse_dict({"a": 1}) == {"a": 1}
        assert _parse_dict(None) == {}
        assert _parse_dict("not dict") == {}


